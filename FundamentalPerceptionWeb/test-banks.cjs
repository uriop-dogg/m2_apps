const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(__dirname+'/app.js','utf8');
const banks=[{id:1,octave:4},{id:2,octave:5}];
const context={banks};vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function unusedOctave'),source.indexOf('function refreshBankControls')),context);
assert.equal(context.unusedOctave(4),6);
assert.match(context.changeBankOctave(banks[1],'4'),/すでに/);
assert.equal(banks[1].octave,5);
for(const invalid of ['', ' ', '2.5', '-1', '9','NaN'])assert.ok(context.changeBankOctave(banks[1],invalid));
assert.equal(context.changeBankOctave(banks[1],'5'),'');
assert.equal(context.changeBankOctave(banks[1],'3'),'');
assert.equal(banks[1].octave,3);
for(const octave of [0,1,2,5,6,7,8])banks.push({octave});
assert.equal(context.unusedOctave(8),null);
banks.splice(banks.findIndex(b=>b.octave===6),1);
assert.equal(context.unusedOctave(8),6);
let stopped=[];
const entry=id=>({bankId:id,voice:{sources:[{stop(){stopped.push(id)},disconnect(){}}]},gain:{disconnect(){}}});
context.voices=new Map([['1:0',entry(1)],['2:0',entry(2)]]);
context.retiringVoices=new Set([entry(1),entry(2)]);
vm.runInContext(source.slice(source.indexOf('function killVoices'),source.indexOf('function setNote')),context);
context.killVoices({id:1});
assert.deepEqual(stopped,[1,1]);assert.equal(context.voices.size,1);assert.equal(context.retiringVoices.size,1);
context.killVoices();assert.equal(context.voices.size,0);assert.equal(context.retiringVoices.size,0);
console.log('Octave uniqueness, range, exhaustion, reuse and independent voice cleanup passed.');
